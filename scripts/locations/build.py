# Builds the location seed SQL (states, districts, cities) for
# supabase/migrations/20261102000100_locations.sql. See docs/locations.md.
# Usage: LOCATION_DATA=<folder with the npm packages unpacked> python3 build.py out.sql
import json, gzip, glob, re, difflib, math, collections, sys
import os
D=os.environ.get('LOCATION_DATA','data')
kit_s=json.load(open(f'{D}/india-location-kit/package/src/data/states.json'))
kit_d=json.load(open(f'{D}/india-location-kit/package/src/data/districts.json'))
# Tripura is missing in the source
for n in ['Dhalai','Gomati','Khowai','North Tripura','Sepahijala','South Tripura','Unakoti','West Tripura']:
    kit_d.append({'stateCode':'TR','name':n})
states={s['code']:s for s in kit_s}
def norm(x):
    x=x.lower().replace('&',' and ')
    x=re.sub(r'\b(district|dist)\b','',x)
    return re.sub(r'[^a-z]','',x)
dist_by_state=collections.defaultdict(list)
for d in kit_d: dist_by_state[d['stateCode']].append(d['name'].strip())
sname_to_code={norm(s['name']):s['code'] for s in kit_s}
# post offices -> state code, district (matched to kit), lat/lng
po=json.load(gzip.open(f'{D}/ip/package/data/pincodes.json.gz'))
alias={'thedadranagarhavelianddaman':'DN','dadraandnagarhaveli':'DN','damananddiu':'DN','delhi':'DL','andamanandnicobarislands':'AN','jammuandkashmir':'JK','ladakh':'LA','puducherry':'PY','pondicherry':'PY','chhattisgarh':'CG','orissa':'OD','odisha':'OD','uttaranchal':'UK','uttarakhand':'UK'}
def scode(name):
    n=norm(name)
    return sname_to_code.get(n) or alias.get(n) or next((v for k,v in alias.items() if k in n),None)
cache={}
def match_d(sc,dname):
    key=(sc,dname)
    if key in cache: return cache[key]
    opts={norm(x):x for x in dist_by_state[sc]}
    n=norm(dname); r=opts.get(n)
    if not r:
        m=difflib.get_close_matches(n,list(opts),1,0.8)
        r=opts[m[0]] if m else None
    cache[key]=r; return r
pts=collections.defaultdict(list)
miss_s=set()
for p in po:
    if not p.get('a') or not p.get('n'): continue
    sc=scode(p['s'])
    if not sc: miss_s.add(p['s']); continue
    d=match_d(sc,p['i'])
    if d: pts[sc].append((p['a'],p['n'],d))
print('unmatched PO states',miss_s,file=sys.stderr)
csc_code={'CT':'CG','OR':'OD','DH':'DN'}
cities=collections.defaultdict(set)  # (sc,district)->names
unassigned=0
for f in glob.glob(f'{D}/csc/package/dist/data/India-IN/*/cities.json'):
    for c in json.load(open(f)):
        sc=csc_code.get(c['state_code'],c['state_code'])
        if sc not in states: print('?',sc,file=sys.stderr); continue
        name=c['name'].strip()
        # city with the same name as a district goes there
        dn=match_d(sc,name)
        if not dn:
            la,ln=float(c['latitude']),float(c['longitude'])
            best=None;bd=1e9
            for a,b,d in pts[sc]:
                dd=(a-la)**2+((b-ln)*math.cos(math.radians(la)))**2
                if dd<bd: bd,best=dd,d
            if best is None or bd>0.25**2: unassigned+=1; continue
            dn=best
        cities[(sc,dn)].add(name)
print('unassigned',unassigned,'cities',sum(map(len,cities.values())),file=sys.stderr)
empty=[(s,d) for s in dist_by_state for d in dist_by_state[s] if not cities.get((s,d))]
# A district with no known town gets its own name, usually its headquarters.
for s,d in empty: cities[(s,d)].add(d)
print('districts without city',len(empty),file=sys.stderr)
def q(x): return "'"+x.replace("'","''")+"'"
out=[]
out.append('-- Generated by scripts/locations/build.py. Do not edit by hand.\n')
out.append('insert into public.location_states (code, name, is_union_territory) values\n'+',\n'.join(
  f"  ({q(s['code'])}, {q(s['name'])}, {'true' if s['type']=='UT' else 'false'})" for s in sorted(kit_s,key=lambda s:s['name']))+'\non conflict do nothing;\n')
rows=[f"  ({q(s)}, {q(d)})" for s in sorted(dist_by_state) for d in sorted(set(dist_by_state[s]))]
out.append('insert into public.location_districts (state_id, name)\nselect s.id, v.name from (values\n'+',\n'.join(rows)+'\n) as v(code, name) join public.location_states s on s.code = v.code\non conflict do nothing;\n')
rows=[f"  ({q(s)}, {q(d)}, {q(c)})" for (s,d) in sorted(cities) for c in sorted(cities[(s,d)])]
out.append('insert into public.location_cities (district_id, name)\nselect d.id, v.name from (values\n'+',\n'.join(rows)+
 '\n) as v(code, district, name)\njoin public.location_states s on s.code = v.code\njoin public.location_districts d on d.state_id = s.id and d.name = v.district\non conflict do nothing;\n')
open(sys.argv[1],'w').write('\n'.join(out))
